// Builds renderer/js/icons.js from the Lucide SVG files in node_modules/lucide-static.
// Run: node scripts/build-icons.js
const fs = require('fs');
const path = require('path');

const NAMES = [
  'house', 'search', 'film', 'tv', 'smile', 'bookmark', 'bookmark-check', 'layout-grid', 'pin', 'pin-off', 'settings',
  'play', 'pause', 'rotate-ccw', 'rotate-cw', 'skip-forward', 'volume-2', 'volume-x', 'gauge', 'captions',
  'list-video', 'picture-in-picture-2', 'maximize', 'minimize', 'arrow-left', 'arrow-right', 'check', 'circle', 'info',
  'server', 'lock', 'shield', 'plus', 'grid-2x2', 'columns-2', 'panels-top-left', 'x', 'chevron-down', 'users',
  'user', 'list', 'log-out', 'folder'
];

const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const out = {};
for (const name of NAMES) {
  const svg = fs.readFileSync(path.join(dir, `${name}.svg`), 'utf8');
  out[name] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
}

const js = `// Generated by scripts/build-icons.js from lucide-static (ISC license). Do not edit.
(function () {
  const PATHS = ${JSON.stringify(out, null, 2)};
  const NS = 'http://www.w3.org/2000/svg';

  // icon('play', { size: 18, stroke: 2 }) -> <svg class="icon">
  function icon(name, { size = 18, stroke = 2, cls = '' } = {}) {
    const svg = document.createElementNS(NS, 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('width', size);
    svg.setAttribute('height', size);
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', stroke);
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('class', ('icon ' + cls).trim());
    svg.innerHTML = PATHS[name] || '';
    return svg;
  }

  window.Sofa = window.Sofa || {};
  window.Sofa.icon = icon;
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'renderer', 'js', 'icons.js'), js);
console.log(`icons.js: ${NAMES.length} icons`);
